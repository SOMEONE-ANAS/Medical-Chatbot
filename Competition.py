import streamlit as st

# إعدادات صفحة الويب
st.set_page_config(
    page_title="مساعد ضغط الدم التعليمي", page_icon="🩺", layout="centered"
)

# شريط جانبي لإخلاء المسؤولية (إلزامي لمتطلبات السلامة الطبية في المشروع)
with st.sidebar:
    st.header("⚠️ إخطار وإخلاء مسؤولية طبي")
    st.write(
        "هذا الروبوت هو نموذج تعليمي بحثي لموضوع (ارتفاع ضغط الدم - High Blood Pressure) ولا يقدم تشخيصاً طبياً نهائياً أو وصفات علاجية. في حالات الطوارئ، يرجى مراجعة الطبيب فوراً."
    )
    st.markdown("---")
    st.info(
        "موضوع المشروع: روبوت محادثة تخصصي لارتفاع ضغط الدم مستند إلى مصادر موثوقة (NHS, CDC)."
    )

st.title("🩺 المساعد التعليمي لارتفاع ضغط الدم")
st.write(
    "أهلاً بك! اطرح سؤالك حول ضغط الدم، الأعراض، أساليب الوقاية، أو طرق المراقبة وسيجيبك النظام استناداً إلى المعايير الطبية المعتمدة."
)

# ذاكرة المحادثة لتخزين الرسائل
if "messages" not in st.session_state:
    st.session_state.messages = []

# عرض المحادثات السابقة
for message in st.session_state.messages:
    with st.chat_message(message["role"]):
        st.markdown(message["content"])

# استقبال مدخلات المستخدم
if prompt := st.chat_input("اكتب سؤالك حول ارتفاع ضغط الدم هنا..."):
    st.session_state.messages.append({"role": "user", "content": prompt})
    with st.chat_message("user"):
        st.markdown(prompt)

    # توليد الرد الذكي المتخصص في ضغط الدم
    with st.chat_message("assistant"):
        p_lower = prompt.lower()

        # إجابات ذكية مصممة خصيصاً لتغطية متطلبات المشروع لضغط الدم
        if "تعريف" in p_lower or "ما هو" in p_lower or "definition" in p_lower:
            response = (
                "**ارتفاع ضغط الدم (High Blood Pressure / Hypertension):** هو حالة شائعة تكون فيها قوة دفع الدم ضد جدران الشرايين عالية لدرجة قد تسبب مشكلات صحية لاحقاً. "
                "يُعرف غالباً بـ 'القاتل الصامت' لأنه قد لا يظهر أعراضاً واضحة لسنوات. (المصدر: CDC / NHS)"
            )
        elif (
            "أعراض" in p_lower or "علامات" in p_lower or "symptoms" in p_lower
        ):
            response = (
                "**الأعراض:** معظم المصابين بارتفاع ضغط الدم لا تظهر عليهم أي أعراض تماماً حتى في الحالات المتقدمة. "
                "ولكن في حالات الارتفاع الشديد جداً (أزمة ارتفاع الضغط)، قد تشمل الأعراض: صداعاً حاداً، ضيقاً في التنفس، أو نزيفاً من الأنف. (المصدر: MedlinePlus)"
            )
        elif (
            "عوامل" in p_lower
            or "خطر" in p_lower
            or "risk" in p_lower
            or "أسباب" in p_lower
        ):
            response = (
                "**عوامل الخطر:** تشمل التقدم في العمر، التاريخ العائلي، السمنة، قلة النشاط البدني، الإكثار من تناول الملح (الملح الصوديومي)، التدخين، والإكثار من الكحول والتوتر المستمر. (المصدر: WHO)"
            )
        elif (
            "قياس" in p_lower
            or "مراقبة" in p_lower
            or "monitoring" in p_lower
            or "قراءات" in p_lower
        ):
            response = (
                "**مراقبة ضغط الدم:** يتم قياسه بجهاز الضغط (Sphygmomanometer) ويعبر عنه برقمين: الضغط الانقباضي (العلوي) والضغط الانبساطي (السفلي). "
                "القراءة الطبيعية غالباً تكون أقل من 120/80 مم زئبق. المراقبة المنزلية المنتظمة ضرورية لمتابعة الحالة. (المصدر: NHS)"
            )
        elif (
            "وقاية" in p_lower
            or "علاج" in p_lower
            or "نمط حياة" in p_lower
            or "prevention" in p_lower
        ):
            response = (
                "**الوقاية والعناية الذاتية:** تشمل اتباع نظام غذائي صحي (مثل حمية ديت DASH الغنية بالخضروات والفواكه)، تقليل استهلاك الملح، ممارسة الرياضة بانتظام، الحفاظ على وزن صحي، والإقلاع عن التدخين. "
                "ملاحظة هامة: لا يجب تناول أي أدوية خافضة للضغط إلا بوصفة وإشراف طبي كامل من الطبيب المعالج. (المصدر: CDC)"
            )
        elif (
            "طارئة" in p_lower
            or "طوارئ" in p_lower
            or "warning" in p_lower
            or "متى تزور الطبيب" in p_lower
        ):
            response = (
                "**علامات التحذير الطارئة:** إذا كان قياس ضغط الدم أعلى بكثير من 180/120 مم زئبق وكان مصحوباً بألم في الصدر، ضيق في التنفس، صعوبة في الكلام، أو ضعف مفاجئ، فهذه حالة طوارئ طبية تتطلب التوجه لأقرب طوارئ فوراً. (المصدر: NHS)"
            )
        else:
            response = (
                f"شكراً لسؤالك حول ({prompt}). بصفتي مساعداً تعليمياً تخصصياً لارتفاع ضغط الدم، أنصحك بالاستناد إلى التوجيهات الطبية الرسمية من منظمة الصحة العالمية (WHO) أو هيئة الخدمات الصحية الوطنية (NHS). "
                "تذكر أن هذه المعلومات لأغراض تعليمية وتوعوية ولا تغني عن استشارة الطبيب."
            )

        st.markdown(response)

    st.session_state.messages.append({"role": "assistant", "content": response})